export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Horizontal advance per character, in font pixels (glyph + 1 gap). */
export const GLYPH_ADVANCE = GLYPH_WIDTH + 1;

const ROWS = new Map<string, number[]>(
  Object.entries(GLYPHS).map(([ch, rows]) => [ch, rows.split(" ").map((r) => parseInt(r, 2))]),
);

/** Rows (5-bit masks, top first) for a supported character, else undefined. */
export function glyphRows(ch: string): readonly number[] | undefined {
  return ROWS.get(ch);
}

/**
 * Text the font can draw: accents stripped, uppercased, anything else
 * replaced with "?" and runs of whitespace collapsed.
 */
export function toFontText(text: string): string {
  return [...text.normalize("NFD").replace(/\p{M}/gu, "").toUpperCase().replace(/\s+/g, " ").trim()]
    .map((ch) => (ROWS.has(ch) ? ch : "?"))
    .join("");
}

/** Width in output pixels of `text` (already font text) at `scale`. */
export function textWidth(text: string, scale: number): number {
  const chars = [...text].length;
  return chars === 0 ? 0 : (chars * GLYPH_ADVANCE - 1) * scale;
}
